// Domain types shared by the engines. These mirror the columns in
// docs/engineering/SYSTEM_DESIGN.md §3.2 but as calendar values, never
// timestamps, and with branded ids so a TaskId can't be passed as a ProjectId.
import type { Instant, LocalDate, LocalTime } from "../time";

export type TaskId = string & { readonly __brand: "TaskId" };
export type ProjectId = string & { readonly __brand: "ProjectId" };
export type SpaceId = string & { readonly __brand: "SpaceId" };
export type BlockId = string & { readonly __brand: "BlockId" };

export type TaskState = "inbox" | "active" | "someday" | "done" | "dropped" | "archived";
export type MissPolicy = "carry" | "skip" | "expire";
export type RecurrenceMode = "fixed" | "after_completion";
export type Priority = 0 | 1 | 2 | 3;

export interface Task {
  id: TaskId;
  spaceId: SpaceId;
  projectId: ProjectId | null;
  title: string;
  notes: string | null;
  state: TaskState;
  priority: Priority;
  doDate: LocalDate | null;
  doTime: LocalTime | null;
  deadline: LocalDate | null;
  startDate: LocalDate | null;
  evening: boolean;
  estimateMin: number | null;
  carryCount: number;
  lastCarriedAt: LocalDate | null;
  lastTouchedAt: Instant;
  missPolicy: MissPolicy;
  recurrenceRule: string | null;
  recurrenceMode: RecurrenceMode | null;
  recurrenceSeriesId: TaskId | null;
  recurrencePausedUntil: LocalDate | null;
  /** Position within the project / heading / inbox. */
  sortKey: string;
  /** Position within a day's unscheduled list. */
  daySortKey: string | null;
  /** Set on occurrences generated by a routine (M2); such tasks are skipped, never carried. */
  routineRunId: string | null;
}

export type RecurrenceException =
  | { occurrenceDate: LocalDate; kind: "skip" }
  | { occurrenceDate: LocalDate; kind: "move"; movedTo: LocalDate };
